# ------------------------------------------------------- fail-closed faults (REVIEW-1 #6)
def _copy_run(repo_root, source, tmp_path):
    import shutil

    work = tmp_path / "run"
    shutil.copytree(repo_root / source, work)
    return work


def _rewrite_results(work, rows):
    (work / "results.jsonl").write_text("\n".join(json.dumps(r) for r in rows) + "\n")


def test_duplicate_per_condition_observation_is_refused(repo_root, tmp_path):
    work = _copy_run(repo_root, PAIRED_RUN, tmp_path)
    rows = [json.loads(l) for l in (work / "results.jsonl").read_text().splitlines() if l.strip()]
    choice_row = next(r for r in rows if r["predictions"]["answer"]["type"] == "choice")
    duplicate = json.loads(json.dumps(choice_row))
    duplicate["predictions"]["answer"]["probabilities"]["yes"] = 0.99  # a DIFFERENT observation
    rows.append(duplicate)
    _rewrite_results(work, rows)
    with pytest.raises(ValueError, match="duplicate observation"):
        reconstruct_paired_boolq(work)


def test_missing_yes_probability_is_invalid_not_defaulted(repo_root, tmp_path):
    work = _copy_run(repo_root, PAIRED_RUN, tmp_path)
    rows = [json.loads(l) for l in (work / "results.jsonl").read_text().splitlines() if l.strip()]
    row = next(r for r in rows if r["predictions"]["answer"]["type"] == "choice")
    row["predictions"]["answer"].pop("probabilities")
    _rewrite_results(work, rows)
    report = reconstruct_paired_boolq(work)
    condition = row["condition"].split(";")[0]
    assert report["per_condition"][condition]["n_invalid_or_missing_rows"] == 1
    assert report["incomplete"] is True
    # the constants must NOT be recomputed with a silent 0.0 substitute
    assert report["per_condition"][condition]["n_valid"] == 499


def test_out_of_range_and_nonfinite_probabilities_are_invalid(repo_root, tmp_path):
    work = _copy_run(repo_root, PAIRED_RUN, tmp_path)
    lines = (work / "results.jsonl").read_text().splitlines()
    records = [json.loads(l) for l in lines]
    choice_row = next(r for r in records if r["predictions"]["answer"]["type"] == "choice")
    noul_row = next(r for r in records if r["predictions"]["answer"]["type"] == "noul")
    choice_row["predictions"]["answer"]["probabilities"]["yes"] = 1.5  # out of range
    noul_row["predictions"]["answer"]["noul"] = float("inf")
    _rewrite_results(work, records)  # inf emits a bare Infinity literal on purpose
    report = reconstruct_paired_boolq(work)
    total_invalid = sum(
        c["n_invalid_or_missing_rows"] for c in report["per_condition"].values()
    )
    assert total_invalid >= 2
    assert report["incomplete"] is True


