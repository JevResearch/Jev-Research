# --------------------------------------------------------- paired BoolQ
def test_paired_boolq_reproduction_constants(repo_root):
    """Saved-artifact regression: exact accuracies and Brier scores rebuild."""
    report = reconstruct_paired_boolq(repo_root / PAIRED_RUN)
    choice = report["per_condition"]["boolq_choice"]
    noul = report["per_condition"]["boolq_noul"]
    assert choice["n_correct"] == REGRESSION_PAIRED_BOOLQ["choice_correct"]
    assert noul["n_correct"] == REGRESSION_PAIRED_BOOLQ["noul_correct"]
    assert choice["n_valid"] == REGRESSION_PAIRED_BOOLQ["n_pairs"]
    assert round(choice["binary_brier_p_yes"], 7) == REGRESSION_PAIRED_BOOLQ["choice_brier"]
    assert round(noul["binary_brier_p_yes"], 7) == REGRESSION_PAIRED_BOOLQ["noul_brier"]
    assert report["n_paired_base_records"] == 500


def test_paired_boolq_provenance_and_counts(repo_root):
    report = reconstruct_paired_boolq(repo_root / PAIRED_RUN)
    assert set(report["input_hashes"]) >= {"manifest.json", "items.jsonl", "results.jsonl"}
    assert all(len(h) == 64 for h in report["input_hashes"].values())
    assert report["claim_type"] == "exploratory"
    assert report["n_independent_calls_per_condition"] == {"boolq_choice": 500, "boolq_noul": 500}
    assert "estimator" in report and "bootstrap" in report["estimator"]["brier"]
    assert report["incomplete"] is False


def test_invalid_observations_are_counted_not_dropped(repo_root, tmp_path):
    """A failed record must surface as n_invalid, never silently vanish."""
    import shutil

    work = tmp_path / "run"
    shutil.copytree(repo_root / PAIRED_RUN, work)
    rows = (work / "results.jsonl").read_text().splitlines()
    row = json.loads(rows[0])
    row["status"] = "error"
    rows[0] = json.dumps(row)
    (work / "results.jsonl").write_text("\n".join(rows) + "\n")
    report = reconstruct_paired_boolq(work)
    condition = row["condition"].split(";")[0]
    assert report["per_condition"][condition]["n_invalid_or_missing_rows"] == 1
    assert report["incomplete"] is True


# --------------------------------------------------------- mechanism v3
def test_mechanism_v3_uses_six_pairs_not_distances(repo_root):
    """Sample units are the six repeat pairs; pairwise-distance n is refused."""
    report = reconstruct_mechanism_v3(repo_root / MECH_RUN)
    assert report["n_repeats"] == 6
    assert report["claim_type"] == "exploratory"
    assert "confound" in report["design_caveat"]
    for anchor, block in report["anchors"].items():
        assert set(block["arms"]) == {"alone", "sib8", "renamed8", "reorder8"}
        for arm, arm_block in block["arms"].items():
            assert arm_block["n_valid"] == 6, (anchor, arm)
        for arm, shift in block["paired_shifts_vs_reference"].items():
            assert shift["n_pairs"] == 6
            assert 0.0 <= shift["sign_flip_exact_p_two_sided"] <= 1.0


def test_mechanism_v3_paired_shifts_match_manual_anchor_means(repo_root):
    """dup-charge renamed8 shift equals mean(treatment) - mean(alone) over pairs."""
    report = reconstruct_mechanism_v3(repo_root / MECH_RUN)
    block = report["anchors"]["dup-charge"]
    alone = block["arms"]["alone"]["p_yes_by_repeat"]
    renamed = block["arms"]["renamed8"]["p_yes_by_repeat"]
    expected = statistics_mean([t - a for t, a in zip(renamed, alone)])
    got = block["paired_shifts_vs_reference"]["renamed8"]["mean_signed_shift"]
    assert abs(got - expected) < 1e-12


def statistics_mean(values):
    return sum(values) / len(values)


# --------------------------------------------------------- strict JSON
def test_strict_json_refuses_nonfinite(tmp_path):
    with pytest.raises(ValueError):
        assert_strict_json({"loss": float("inf")})
    with pytest.raises(ValueError):
        assert_strict_json({"a": [float("nan")]})
    # serialisation path represents nonfinite explicitly, never as literals
    dump_strict_json({"loss": {"nonfinite": "inf"}}, tmp_path / "x.json")
    assert "Infinity" not in (tmp_path / "x.json").read_text()


def test_nonfinite_represented_explicitly():
    assert finite_or_marker(float("inf")) == {"nonfinite": "inf"}
    assert finite_or_marker(float("-inf")) == {"nonfinite": "-inf"}
    assert finite_or_marker(float("nan")) == {"nonfinite": "nan"}
    dumped = json.dumps(finite_or_marker({"x": float("inf")}), allow_nan=False)
    assert "Infinity" not in dumped and json.loads(dumped)["x"] == {"nonfinite": "inf"}


