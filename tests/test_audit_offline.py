def test_empty_paired_sample_is_unavailable_not_crash(repo_root, tmp_path):
    work = _copy_run(repo_root, PAIRED_RUN, tmp_path)
    rows = [json.loads(l) for l in (work / "results.jsonl").read_text().splitlines() if l.strip()]
    kept = [r for r in rows if str(r["condition"]).split(";")[0] != "boolq_noul"]
    _rewrite_results(work, kept)
    report = reconstruct_paired_boolq(work)
    assert report["result_available"] is False
    assert report["per_condition"] is None and report["paired"] is None
    assert "empty paired sample" in report["unavailable_reason"]
    assert report["incomplete"] is True


